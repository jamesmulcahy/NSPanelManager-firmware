#!/usr/bin/env python3
"""Rasterise icons from a TrueType icon font (Material Design Icons) into an LVGL font in C, at a
given size and bits per pixel, and write the header that names them.

LVGL's built-in fonts carry only ~60 FontAwesome symbols, none of them for weather, lights,
thermostats or covers. NSPM's web UI already ships MDI (materialdesignicons-webfont.ttf in the
manager repository), so the pages use MDI glyphs, cut to the icons each size needs.

MDI's code points are above U+FFFF (4-byte UTF-8). The icons are renumbered from U+E000 in the
order of the icon table (tools/nspm_icons.txt), so every size shares one numbering and the
header's NSPM_ICON_* strings work with any of the icon fonts.

    tools/lv_icon_font.py --ttf MDI.ttf --size 24 --bpp 2 --table tools/nspm_icons.txt \
        --icons all|name,name,... NAME > lib/LvglRenderer/NAME.c
    tools/lv_icon_font.py --table tools/nspm_icons.txt --header > lib/LvglRenderer/nspm_icons.h

With --codes instead of --table, rasterises text glyphs at their own code points (no renumbering),
e.g. from Montserrat: what LVGL's built-in fonts lack (Latin-1, typographic quotes and dashes).

    tools/lv_icon_font.py --ttf Montserrat-Medium.ttf --size 14 --bpp 1 \
        --codes 00A0-00FF,2013-2014,2018-201E,2022,2026 NAME > lib/LvglRenderer/NAME.c

Needs Pillow with FreeType (qemu/.venv has it).
"""
import argparse
import sys

FIRST = 0xE000


def read_table(path):
    icons = []
    for line in open(path):
        line = line.split("#")[0].strip()
        if line:
            name, code = line.split()
            icons.append((name, int(code, 16)))
    return icons


def utf8_escape(code):
    return "".join("\\x%02X" % b for b in chr(code).encode("utf-8"))


def header(icons):
    out = ["/* Generated by tools/lv_icon_font.py from tools/nspm_icons.txt. Do not edit. */",
           "/* Material Design Icons, renumbered from U+E000; use with Theme::icon_font(). */",
           "#pragma once", ""]
    for i, (name, code) in enumerate(icons):
        macro = "NSPM_ICON_" + name.upper().replace("-", "_")
        out.append('#define %-40s "%s" /* mdi-%s, U+%05X */' % (macro, utf8_escape(FIRST + i), name, code))
    return "\n".join(out)


def pack(values, bpp):
    out, acc, bits = [], 0, 0
    for v in values:
        acc = (acc << bpp) | v
        bits += bpp
        while bits >= 8:
            bits -= 8
            out.append((acc >> bits) & 0xFF)
    if bits:
        out.append((acc << (8 - bits)) & 0xFF)
    return out


def parse_codes(spec):
    codes = []
    for part in spec.split(","):
        lo, _, hi = part.partition("-")
        codes += range(int(lo, 16), int(hi or lo, 16) + 1)
    return sorted(set(codes))


def font_c(args, icons):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(args.ttf, args.size)
    ascent, descent = font.getmetrics()
    if args.codes:
        items = [("U+%04X" % c, c, c, font) for c in parse_codes(args.codes)]
        if args.sym_ttf:
            # LVGL's symbols (FontAwesome, as its built-in fonts carry them), drawn at the same size.
            sym = ImageFont.truetype(args.sym_ttf, args.size)
            items += [("U+%04X" % c, c, c, sym) for c in parse_codes(args.sym_codes)]
            items.sort(key=lambda item: item[1])
    else:
        items = [(name, code, FIRST + i, font) for i, (name, code) in enumerate(icons)]
    wanted = None if args.codes or args.icons == "all" else set(args.icons.split(","))
    if wanted is not None:
        unknown = wanted - {n for n, _ in icons}
        if unknown:
            sys.exit("not in the table: %s" % ", ".join(sorted(unknown)))
    top = (1 << args.bpp) - 1

    bitmap = []
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */"]
    codes = []
    for name, code, out_code, glyph_font in items:
        if wanted is not None and name not in wanted:
            continue
        size = args.size * 3
        img = Image.new("L", (size, size), 0)
        ox, oy = args.size, args.size * 2  # pen origin on the baseline
        ImageDraw.Draw(img).text((ox, oy), chr(code), font=glyph_font, fill=255, anchor="ls")
        box = img.getbbox()
        adv = int(round(glyph_font.getlength(chr(code)) * 16))
        if box is None:
            data, bw, bh, ofs_x, ofs_y = [], 0, 0, 0, 0
        else:
            x0, y0, x1, y1 = box
            bw, bh = x1 - x0, y1 - y0
            px = img.crop(box).tobytes()
            data = pack([(v * top + 127) // 255 for v in px], args.bpp)
            ofs_x, ofs_y = x0 - ox, oy - y1
        dsc.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d} /* %s */" % (
            len(bitmap), adv, bw, bh, ofs_x, ofs_y, name))
        bitmap += data
        codes.append(out_code)
    if not codes:
        sys.exit("no icons")

    first = codes[0]
    lines = []
    w = lines.append
    w("/* Generated by tools/lv_icon_font.py: %d %s at %d px, %d bpp. Do not edit. */" % (len(codes), "glyphs" if args.codes else "MDI icons", args.size, args.bpp))
    w("#include <lvgl.h>")
    if args.guard:
        w("#if defined(%s)" % args.guard)
    w("")
    w("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        w("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    w(",\n".join(dsc))
    w("};")
    w("")
    w("static const uint16_t unicode_list[] = {")
    offsets = ["0x%x" % (c - first) for c in codes]
    for i in range(0, len(offsets), 12):
        w("    " + ", ".join(offsets[i:i + 12]) + ",")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    w("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, .unicode_list = unicode_list," % (first, codes[-1] - first + 1))
    w("     .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}," % len(codes))
    w("};")
    w("")
    w("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    w("    .glyph_bitmap = glyph_bitmap,")
    w("    .glyph_dsc = glyph_dsc,")
    w("    .cmaps = cmaps,")
    w("    .kern_dsc = NULL,")
    w("    .kern_scale = 0,")
    w("    .cmap_num = 1,")
    w("    .bpp = %d," % args.bpp)
    w("    .kern_classes = 0,")
    w("    .bitmap_format = 0,")
    w("};")
    w("")
    w("const lv_font_t %s = {" % args.name)
    w("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    w("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    w("    .line_height = %d," % (ascent + descent))
    w("    .base_line = %d," % descent)
    w("    .subpx = LV_FONT_SUBPX_NONE,")
    w("    .underline_position = 0,")
    w("    .underline_thickness = 0,")
    w("    .static_bitmap = 1,")
    w("    .dsc = &font_dsc,")
    w("    .fallback = NULL,")
    w("    .user_data = NULL,")
    w("};")
    if args.guard:
        w("#endif")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--table")
    ap.add_argument("--codes", help="hex code points and ranges to rasterise as they are, e.g. 00A0-00FF,2019")
    ap.add_argument("--header", action="store_true", help="write nspm_icons.h instead of a font")
    ap.add_argument("--sym-ttf", help="with --codes: a second font for --sym-codes (LVGL's FontAwesome symbols)")
    ap.add_argument("--sym-codes", default="")
    ap.add_argument("--guard", help="wrap the font in #if defined(GUARD), so only builds that define it compile it")
    ap.add_argument("--ttf")
    ap.add_argument("--size", type=int)
    ap.add_argument("--bpp", type=int, choices=(1, 2, 4), default=2)
    ap.add_argument("--icons", default="all")
    ap.add_argument("name", nargs="?")
    args = ap.parse_args()
    icons = read_table(args.table) if args.table else []
    if args.header:
        print(header(icons))
    else:
        if not (args.ttf and args.size and args.name):
            sys.exit("--ttf, --size and NAME are needed for a font")
        print(font_c(args, icons))


if __name__ == "__main__":
    main()
