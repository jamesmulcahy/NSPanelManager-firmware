# Embed the setup web UI in the firmware image.
#
# Gzips web/index.html and web/static/main.css and writes them as byte arrays to
# include/generated/web_assets.hpp, which WebManager serves as they are with
# `Content-Encoding: gzip` (the browser does the decompressing). A generated header rather than
# EMBED_FILES: it needs no second declaration in CMakeLists.txt, ordinary header dependency
# tracking rebuilds what includes it, and it works the same in the qemu environment.
#
# The output is reproducible (gzip.compress with mtime=0 writes no name or timestamp), and the
# header is rewritten only when its content changes, so an unchanged UI forces no rebuild.
# main.css is Tailwind's output and is committed; the build never runs npm (see tailwind_devel.sh).
import gzip
import os

Import("env")

_project_dir = env.subst("$PROJECT_DIR")
_web_dir = os.path.join(_project_dir, "web")
_out_path = os.path.join(_project_dir, "include", "generated", "web_assets.hpp")

# (C++ name, source file relative to web/)
_ASSETS = [
    ("INDEX_HTML", "index.html"),
    ("MAIN_CSS", os.path.join("static", "main.css")),
]


def _render():
    lines = [
        "// Generated by gen_web_assets.py from web/. Do not edit, do not commit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace web_assets {",
        "",
    ]
    for name, relative_path in _ASSETS:
        with open(os.path.join(_web_dir, relative_path), "rb") as f:
            compressed = gzip.compress(f.read(), 9, mtime=0)
        lines.append("// web/%s, gzip -9: %d bytes." % (relative_path.replace(os.sep, "/"), len(compressed)))
        lines.append("static const uint8_t %s_GZ[] = {" % name)
        for i in range(0, len(compressed), 16):
            lines.append("  " + ", ".join("0x%02x" % b for b in compressed[i:i + 16]) + ",")
        lines.append("};")
        lines.append("static const size_t %s_GZ_LEN = sizeof(%s_GZ);" % (name, name))
        lines.append("")
    lines.append("} // namespace web_assets")
    lines.append("")
    return "\n".join(lines)


_content = _render()
try:
    with open(_out_path, "r") as f:
        _unchanged = f.read() == _content
except OSError:
    _unchanged = False

if not _unchanged:
    os.makedirs(os.path.dirname(_out_path), exist_ok=True)
    with open(_out_path, "w") as f:
        f.write(_content)
